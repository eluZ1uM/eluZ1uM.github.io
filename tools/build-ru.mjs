// Builds the Russian pages (ru/…) and sitemap.xml from the English pages and i18n/ru.json.
// Run from the repository root after editing any page or translation:  node tools/build-ru.mjs
//
// Markup conventions in the English pages:
//   data-i18n="key"             element text is replaced with RU[key] (leaf elements only)
//   data-i18n-attr="a:key;b:k2" attribute a gets RU[key], b gets RU[k2]
//   data-ru-NAME="value"        attribute NAME gets value on the Russian page (image paths are written
//                               as on the English page; page links are written relative to the Russian page)
// Relative links to files (assets) get one extra "../"; relative links to pages stay as they are,
// because ru/ mirrors the English page tree.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const SITE = "https://eluz1um.github.io/";
const PAGES = ["index.html", "scribnox/index.html", "helmavio/index.html"];
const RU = JSON.parse(readFileSync("i18n/ru.json", "utf8"));
const used = new Set();
const errors = [];

const tr = (key, page) => {
  used.add(key);
  if (!(key in RU)) errors.push(`${page}: no Russian text for "${key}"`);
  return RU[key] ?? key;
};
const attrEscape = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const isAsset = (url) => {
  if (/^([a-z]+:|#|\/)/i.test(url)) return false;
  const path = url.split(/[?#]/)[0];
  return path !== "" && !path.endsWith("/") && /\.[a-z0-9]+$/i.test(path);
};
const URL_ATTRS = new Set(["src", "href"]);

function translateTag(tag, page) {
  // tag: the full start tag, e.g. <img src="…" data-ru-src="…">
  const m = /^<([a-zA-Z][\w-]*)([\s\S]*?)(\/?)>$/.exec(tag);
  const attrs = [];
  for (const a of m[2].matchAll(/([^\s=]+)(?:\s*=\s*"([^"]*)")?/g)) attrs.push([a[1], a[2]]);
  const get = (n) => attrs.find((a) => a[0] === n);
  const set = (n, v) => { const a = get(n); if (a) a[1] = v; else attrs.push([n, v]); };
  const drop = (n) => { const i = attrs.findIndex((a) => a[0] === n); if (i >= 0) attrs.splice(i, 1); };

  for (const [n, v] of attrs.filter(([n]) => n.startsWith("data-ru-"))) { drop(n); set(n.slice(8), v); }
  const map = get("data-i18n-attr");
  if (map) {
    drop("data-i18n-attr");
    for (const pair of map[1].split(";")) { const [n, k] = pair.split(":"); set(n.trim(), attrEscape(tr(k.trim(), page))); }
  }
  for (const a of attrs) if (URL_ATTRS.has(a[0]) && a[1] !== undefined && isAsset(a[1])) a[1] = "../" + a[1];

  const body = attrs.map(([n, v]) => (v === undefined ? n : `${n}="${v}"`)).join(" ");
  return `<${m[1]}${body ? " " + body : ""}${m[3]}>`;
}

function build(page) {
  let html = readFileSync(page, "utf8");
  // Text of leaf elements first, while data-i18n is still on the start tags.
  html = html.replace(/<([a-zA-Z][\w-]*)([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>([^<]*)<\/\1>/g,
    (_, name, before, key, after) => `<${name}${before}${after}>${tr(key, page)}</${name}>`);
  // Then every start tag outside <script>/<style> bodies.
  html = html.replace(/(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>)|<[a-zA-Z][\w-]*(?:\s+[^\s=>]+(?:\s*=\s*"[^"]*")?)*\s*\/?>/g,
    (tag, raw) => {
      if (!raw) return translateTag(tag, page);
      // Keep script/style bodies as they are but still translate their own start tag.
      return raw.replace(/^<[^>]*>/, (open) => translateTag(open, page));
    });
  if (/data-i18n|data-ru-/.test(html)) errors.push(`${page}: untranslated data-i18n / data-ru- attribute left (nested markup inside a data-i18n element?)`);
  html = html.replace(/^<!doctype html>\n/i, `<!doctype html>\n<!-- Generated by tools/build-ru.mjs from /${page} and i18n/ru.json. Do not edit by hand. -->\n`);
  const out = "ru/" + page;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
  console.log("wrote", out);
}

PAGES.forEach(build);

const unused = Object.keys(RU).filter((k) => !used.has(k));
if (unused.length) console.warn("unused keys in i18n/ru.json:", unused.join(", "));

const url = (p) => SITE + p.replace(/index\.html$/, "");
const today = new Date().toISOString().slice(0, 10);
const entry = (loc, p) => `  <url>
    <loc>${loc}</loc>
    <lastmod>${today}</lastmod>
    <xhtml:link rel="alternate" hreflang="en" href="${url(p)}"/>
    <xhtml:link rel="alternate" hreflang="ru" href="${url("ru/" + p)}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${url(p)}"/>
  </url>`;
writeFileSync("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${PAGES.flatMap((p) => [entry(url(p), p), entry(url("ru/" + p), p)]).join("\n")}
</urlset>
`);
console.log("wrote sitemap.xml");

if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
